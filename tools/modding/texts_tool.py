"""Six Guns string tables (`texts` in the OBB): dump to editable TSV and rebuild.

    python -I texts_tool.py dump  <texts> <folder>
    python -I texts_tool.py build <folder> <texts>

Format (found from pig::stream::LibStreamLoader2 and StringMgr::LoadStringPack):
  u16 entry_count, u32 offset[entry_count] (relative to the end of this table)
  entry 0:   u16 languages (15), u16 packs (14)
  entries 1 .. languages*packs: one string pack per language, packs in a fixed order per
             language: u8 pack_id, u32 count, u32 end_offset[count], string bytes (UTF-8, each
             string NUL-terminated; end offsets are relative to the start of the string bytes)
  next entry: names: per string u16 len, name bytes, u16 id
  any further entries are kept as they are (the game's file has one empty entry)
String id = pack_id << 11 | index: what StringMgr::GetString / LayerButton::SetTextID take.

Dump writes:
  info.json                    languages, packs, pack order, extra entries (base64)
  <lang>.tsv  (en, fr, ...)    id <TAB> name <TAB> text   (\\n \\t \\\\ escaped)
  string_ids.h                 #define STR_... 0x....   (for port code)
Edit any <lang>.tsv (texts can be any length). To add a string, add a row to en.tsv with an
empty id, a new NAME and the pack after a colon in the id column (e.g. `:5`); build gives it the
next free index in that pack and copies it (same text) into languages that lack it.
"""
import base64
import json
import os
import struct
import sys

LANGS = ['en', 'fr', 'de', 'it', 'es', 'pt', 'ja', 'zh_CN', 'ko', 'ru', 'tr', 'ar', 'th', 'zh_TW', 'id']


def esc(s):
    return s.replace('\\', '\\\\').replace('\t', '\\t').replace('\n', '\\n').replace('\r', '\\r')


def unesc(s):
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c == '\\' and i + 1 < len(s):
            n = s[i + 1]
            out.append({'n': '\n', 't': '\t', 'r': '\r', '\\': '\\'}.get(n, '\\' + n))
            i += 2
        else:
            out.append(c)
            i += 1
    return ''.join(out)


def read_entries(t):
    n = t[0] | (t[1] << 8)
    offs = list(struct.unpack_from(f'<{n}I', t, 2))
    base = 2 + 4 * n
    ends = offs[1:] + [len(t) - base]
    return [t[base + a:base + b] for a, b in zip(offs, ends)]


def write_entries(entries):
    offs, pos = [], 0
    for e in entries:
        offs.append(pos)
        pos += len(e)
    return struct.pack('<H', len(entries)) + struct.pack(f'<{len(entries)}I', *offs) + b''.join(entries)


def parse_pack(e):
    pid = e[0]
    cnt = struct.unpack_from('<I', e, 1)[0]
    ends = struct.unpack_from(f'<{cnt}I', e, 5)
    data = e[5 + 4 * cnt:]
    out, s = [], 0
    for x in ends:
        raw = data[s:x]
        out.append(raw[:-1] if raw.endswith(b'\0') else raw)
        s = x
    return pid, out


def build_pack(pid, strings):
    data, ends = b'', []
    for s in strings:
        data += s + b'\0'
        ends.append(len(data))
    return bytes([pid]) + struct.pack('<I', len(strings)) + struct.pack(f'<{len(strings)}I', *ends) + data


def dump(src, out):
    t = open(src, 'rb').read()
    ent = read_entries(t)
    nl, npk = struct.unpack_from('<HH', ent[0])
    order = [ent[1 + k][0] for k in range(npk)]
    packs = {}  # (lang, pid) -> [bytes]
    for lang in range(nl):
        for k in range(npk):
            pid, strs = parse_pack(ent[1 + lang * npk + k])
            packs[(lang, pid)] = strs
    names_e = ent[1 + nl * npk]
    names, p = {}, 0
    while p + 2 <= len(names_e):
        L = struct.unpack_from('<H', names_e, p)[0]
        nm = names_e[p + 2:p + 2 + L].decode('ascii')
        sid = struct.unpack_from('<H', names_e, p + 2 + L)[0]
        names[sid] = nm
        p += 4 + L
    name_order = []
    p = 0
    while p + 2 <= len(names_e):
        L = struct.unpack_from('<H', names_e, p)[0]
        name_order.append(struct.unpack_from('<H', names_e, p + 2 + L)[0])
        p += 4 + L
    os.makedirs(out, exist_ok=True)
    extra = [base64.b64encode(e).decode() for e in ent[2 + nl * npk:]]
    json.dump({'languages': LANGS[:nl], 'packs': npk, 'pack_order': order, 'name_order': name_order,
               'extra_entries': extra}, open(os.path.join(out, 'info.json'), 'w'), indent=1)
    for lang in range(nl):
        with open(os.path.join(out, f'{LANGS[lang]}.tsv'), 'w', encoding='utf-8', newline='\n') as f:
            f.write('id\tname\ttext\n')
            for pid in sorted({pid for (l, pid) in packs if l == lang}):
                for i, s in enumerate(packs[(lang, pid)]):
                    sid = pid << 11 | i
                    f.write(f'{sid:#06x}\t{names.get(sid, "")}\t{esc(s.decode("utf-8", "surrogateescape"))}\n')
    with open(os.path.join(out, 'string_ids.h'), 'w') as f:
        f.write('/* Six Guns string ids (texts): id = pack << 11 | index. Generated by texts_tool.py. */\n')
        for sid in sorted(names):
            f.write(f'#define {names[sid]} {sid:#06x}\n')
    print(f'{nl} languages x {npk} packs, {len(names)} strings -> {out}')


def build(src, out):
    info = json.load(open(os.path.join(src, 'info.json')))
    langs, order = info['languages'], info['pack_order']
    tables, names, new_rows = [], {}, []
    for li, lang in enumerate(langs):
        per = {}
        for line in open(os.path.join(src, f'{lang}.tsv'), encoding='utf-8').read().split('\n')[1:]:
            if not line:
                continue
            sid, nm, text = (line.split('\t', 2) + ['', ''])[:3]
            raw = unesc(text).encode('utf-8', 'surrogateescape')
            if sid.startswith(':'):  # new string: ":<pack>"
                new_rows.append((li, int(sid[1:]), nm, raw))
                continue
            sid = int(sid, 16)
            per[sid] = raw
            if nm:
                names[sid] = nm
        tables.append(per)
    # assign ids to new strings (from the first language that has them, normally en)
    for li, pid, nm, raw in new_rows:
        existing = [s for s, n in names.items() if n == nm]
        if existing:
            sid = existing[0]
        else:
            used = [s & 2047 for t in tables for s in t if s >> 11 == pid]
            sid = pid << 11 | (max(used) + 1 if used else 0)
            names[sid] = nm
            info['name_order'].append(sid)
            print(f'new string {nm} = {sid:#06x}')
        tables[li][sid] = raw
    for t in tables[1:]:  # languages lacking a string get the first language's text
        for sid, raw in tables[0].items():
            t.setdefault(sid, raw)
    entries = [struct.pack('<HH', len(langs), len(order))]
    for t in tables:
        for pid in order:
            ids = sorted(s & 2047 for s in t if s >> 11 == pid)
            if ids != list(range(len(ids))):
                sys.exit(f'pack {pid}: string indices must be 0..n-1 without gaps')
            entries.append(build_pack(pid, [t[pid << 11 | i] for i in ids]))
    ne = b''
    for sid in info['name_order']:
        nm = names[sid].encode('ascii')
        ne += struct.pack('<H', len(nm)) + nm + struct.pack('<H', sid)
    entries.append(ne)
    entries += [base64.b64decode(e) for e in info['extra_entries']]
    open(out, 'wb').write(write_entries(entries))
    print(f'built {out}: {len(langs)} languages, {len(names)} strings')


if __name__ == '__main__':
    cmd, a, b = sys.argv[1:4]
    {'dump': dump, 'build': build}[cmd](a, b)
